import {
  readFile,
  writeFile,
  mkdir,
  readdir,
  copyFile,
} from "node:fs/promises";
import sharp from "sharp";
const root = process.cwd();
const jobs = JSON.parse(
  await readFile("design/v3/generation-jobs.json", "utf8"),
);
let diverse = [],
  overrides = {};
try {
  diverse = JSON.parse(
    await readFile("design/v3/diverse-portfolio-jobs.json", "utf8"),
  );
} catch {}
try {
  overrides = JSON.parse(
    await readFile("design/v3/generation-overrides.json", "utf8"),
  );
} catch {}
const refs = [
  "/Users/tobin/Downloads/hf_20260420_131356_3b50b8d7-1d55-4a2c-8f55-29e232ca0bb4.png",
  "/Users/tobin/Downloads/hf_20260423_133200_479b4afc-ce60-4fe1-965f-2dfbd5f065cb.png",
];
await mkdir("public/assets/v3/portfolio", { recursive: true });
await mkdir("design/v3/references", { recursive: true });
for (let i = 0; i < refs.length; i++)
  await copyFile(refs[i], `design/v3/references/influencer-${i + 1}.png`);
const all = [
  ...jobs,
  {
    id: "professional-profile",
    serviceId: "professional",
    setting: "portfolio",
    option: "linkedin",
    prompt:
      "Identity-preserve professional portrait of the supplied adult AI influencer in black blazer and cream shirt, natural facial identity, gray seamless backdrop, soft studio light, 85mm portrait, no text or logos.",
    references: refs,
  },
  {
    id: "influencer-source",
    serviceId: "professional",
    setting: "source",
    option: "source",
    prompt:
      "Original user-supplied synthetic influencer identity reference. Resized for before-and-after presentation; not generated by Aichemy and not a customer testimonial.",
    references: refs,
  },
  {
    id: "influencer-cutout",
    serviceId: "formal",
    setting: "background",
    option: "preview-subject",
    prompt:
      "Identity-preserve transparent cutout of the supplied adult AI influencer, frontal head-and-chest, neutral expression, white high-neck shirt and dark blazer, natural skin pores, genuine alpha background, hair edges retained.",
    references: [refs[1]],
  },
];
const available = new Set(await readdir("design/v3/originals"));
let reviews = {};
try {
  reviews = JSON.parse(await readFile("design/v3/visual-reviews.json", "utf8"));
} catch {}
const manifest = [];
for (const job of all) {
  const replacement = diverse.find((j) => j.id === job.id);
  const selected = replacement ?? overrides[job.id] ?? job;
  const version = replacement ? "-v2" : "";
  const original =
    job.id === "influencer-source"
      ? "design/v3/references/influencer-1.png"
      : `design/v3/originals${replacement ? "-v2" : ""}/${job.id}.png`;
  try {
    await readFile(original);
  } catch {
    console.log(`Pending: ${job.id}${version}`);
    continue;
  }
  const src = `/assets/v3/portfolio/${job.id}${version}.webp`;
  for (const width of [1000, 450])
    await sharp(original)
      .rotate()
      .resize({
        width,
        height: Math.round(width * 1.25),
        fit: "cover",
        position: "attention",
      })
      .webp({ quality: width === 1000 ? 86 : 78 })
      .toFile(
        `public${src.replace(".webp", width === 450 ? "-small.webp" : ".webp")}`,
      );
  const reviewKey = `${job.id}${version}`;
  manifest.push({
    id: job.id,
    serviceId: job.serviceId,
    setting: job.setting,
    option: job.option,
    src,
    source: `${root}/${original}`,
    prompt: selected.prompt,
    poseReference: replacement?.poseReference,
    references: (selected.references ?? job.references ?? []).map((ref) =>
      refs.includes(ref)
        ? `${root}/design/v3/references/influencer-${refs.indexOf(ref) + 1}.png`
        : ref,
    ),
    tool:
      job.id === "influencer-source"
        ? "user-provided synthetic reference"
        : "built-in image_gen",
    reviewed: !!reviews[reviewKey],
    reviewNotes: reviews[reviewKey] ?? "Pending visual review.",
  });
}
await writeFile(
  "design/v3/portfolio-assets.json",
  JSON.stringify(manifest, null, 2) + "\n",
);
const columns = 6,
  cell = 190,
  labelHeight = 35;
const rows = Math.ceil(manifest.length / columns);
const tiles = [];
for (let i = 0; i < manifest.length; i++) {
  const job = manifest[i];
  const image = await sharp(`public${job.src}`)
    .resize(cell, 230, { fit: "cover" })
    .png()
    .toBuffer();
  tiles.push({
    input: image,
    left: (i % columns) * cell,
    top: Math.floor(i / columns) * (230 + labelHeight),
  });
  const label = Buffer.from(
    `<svg width="190" height="35"><rect width="190" height="35" fill="white"/><text x="6" y="22" font-family="sans-serif" font-size="11" fill="#222">${job.id}</text></svg>`,
  );
  tiles.push({
    input: label,
    left: (i % columns) * cell,
    top: Math.floor(i / columns) * (230 + labelHeight) + 230,
  });
}
if (manifest.length)
  await sharp({
    create: {
      width: columns * cell,
      height: rows * (230 + labelHeight),
      channels: 3,
      background: "#faf8f5",
    },
  })
    .composite(tiles)
    .png()
    .toFile("design/v3/review-contact-sheet.png");
console.log(`${manifest.length}/${all.length} assets prepared`);
